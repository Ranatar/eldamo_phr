"""Reverse reconstruction: a primitive form for a word that has no derivation.

Most words of Eldamo (lindë, Ambar ...) have no derivation from a primitive
form, so they cannot be joined at an early stage. backform proposes
primitive forms by analysis through synthesis:

1. Correspondences are learnt from the attested derivations of the branch:
   each start form is aligned with the final form, and every final sound
   (in its position: initial, medial, final) records which primitive
   segments it came from, with counts (Q. v < b, w, β; S. -∅ < -a, -e ...).
2. Candidates for a new word are generated by a beam search over these
   correspondences, most probable first.
3. Each candidate runs forward through the sequencer; only candidates that
   reproduce the word are kept (main reading first, then other variants).

The result is a hypothesis with its probability and the rules of the forward
run, never a fact: the generator marks forms built on it as reconstructed.
"""
from __future__ import annotations

import math
from collections import Counter, defaultdict

from .interpreter import comparable, is_vowel, join, phonemes
from .junctions import _align

BEAM = 60
MAX_OPTIONS = 4
MIN_SHARE = 0.03


def _position(i: int, n: int) -> str:
    return 'initial' if i == 0 else 'final' if i == n - 1 else 'medial'


def learn(derivations: list, langs: dict, final_code: str, exclude=frozenset()) -> dict:
    """{(final sound, position): Counter(primitive segment)} plus word-end additions."""
    table = defaultdict(Counter)
    for d in derivations:
        if d['deleted'] or d['id'] in exclude or not d['steps'] or d['steps'][-1]['lang'] != final_code:
            continue
        if langs.get(d['steps'][0]['lang'], {}).get('stage', 99) > 1:
            continue                                    # starts must be (near) primitive
        x = phonemes(comparable(d['start']))
        y = phonemes(comparable(d['steps'][-1]['after']))
        if not x or not y:
            continue
        al, cost = _align(x, y)
        if cost > 0.6 * max(len(x), len(y)):
            continue
        # group: every final sound takes the primitive sounds aligned to it and
        # any deleted primitive sounds before it; deletions after the last final
        # sound attach to the word end
        pending, n = [], len(y)
        for xi, yj in al:
            if yj is None:
                pending.append(x[xi])
                continue
            seg = pending + ([x[xi]] if xi is not None else [])
            pending = []
            table[(y[yj], _position(yj, n))][join(seg)] += 1
        table[('#', 'end')][join(pending)] += 1
    return table


def _options(table: dict, sound: str, pos: str) -> list:
    c = table.get((sound, pos)) or table.get((sound, 'medial')) or Counter({sound: 1})
    total = sum(c.values())
    out = [(seg, n / total) for seg, n in c.most_common() if n / total >= MIN_SHARE]
    if sound not in [s for s, _ in out]:
        out.append((sound, 0.5 / total))         # the sound itself stays possible
    return out[:MAX_OPTIONS]


def candidates(table: dict, form: str, beam: int = BEAM) -> list:
    """[(primitive candidate, log probability)] by beam search."""
    y = phonemes(comparable(form))
    states = [('', 0.0)]
    for j, sound in enumerate(y):
        nxt = []
        for prefix, lp in states:
            for seg, p in _options(table, sound, _position(j, len(y))):
                nxt.append((prefix + seg, lp + math.log(p)))
        nxt.sort(key=lambda s: -s[1])
        states = nxt[:beam]
    end = table.get(('#', 'end')) or Counter({'': 1})
    total = sum(end.values())
    out = []
    for prefix, lp in states:
        for seg, n in end.most_common(MAX_OPTIONS):
            if n / total >= MIN_SHARE:
                out.append((prefix + seg, lp + math.log(n / total)))
    out.sort(key=lambda s: -s[1])
    seen, uniq = set(), []
    for f, lp in out:
        if f and f not in seen:
            seen.add(f)
            uniq.append((f, lp))
    return uniq[:beam]


def backform(seq, table: dict, form: str, era: str, last_stage: int, limit: int = 5) -> list:
    """Verified primitive forms: [{'primitive', 'logp', 'main', 'trace'}]."""
    target = comparable(form)
    rules = seq.sequence(era, 0, last_stage)
    found = []
    for cand, lp in candidates(table, form):
        vs = seq.run(cand, rules)
        hit = next((k for k, v in enumerate(vs) if comparable(v['form']) == target), None)
        if hit is None:
            continue
        found.append({'primitive': cand, 'logp': round(lp, 3), 'main': hit == 0, 'trace': vs[hit]['trace']})
        if len(found) >= limit:
            break
    found.sort(key=lambda f: (not f['main'], -f['logp']))
    return found


def evaluate(data: dict, seq, final_code: str, sample: int = 300) -> dict:
    """Hold out every other derivation: learn on the rest, backform the held-out
    final forms and look for their attested start among verified candidates."""
    langs = seq.langs
    ders = [d for d in data['derivations'] if not d['deleted'] and d['steps']
            and d['steps'][-1]['lang'] == final_code
            and langs.get(d['steps'][0]['lang'], {}).get('stage', 99) <= 1]
    held = ders[1::2][:sample]
    table = learn(data['derivations'], langs, final_code, exclude={d['id'] for d in held})
    era = langs[final_code]['era']
    stage = langs[final_code]['stage']
    stats = Counter()
    for d in held:
        res = backform(seq, table, d['steps'][-1]['after'], era, stage, limit=8)
        stats['cases'] += 1
        if res:
            stats['verified'] += 1
        prims = [comparable(r['primitive']) for r in res]
        if prims and prims[0] == comparable(d['start']):
            stats['first'] += 1
        if comparable(d['start']) in prims:
            stats['any'] += 1
    return dict(stats)
